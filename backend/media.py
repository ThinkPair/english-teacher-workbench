import io
from pathlib import Path

import fitz
from fastapi import HTTPException
from PIL import Image, ImageOps

from . import storage as s

MAX_FILE_SIZE = 20 * 1024 * 1024
MAX_PDF_PAGES = 30
MAX_RECOGNITION_PAGES = 8


def attachment_public(record, workspace):
    url = f"/api/files/{record['id']}?workspace={workspace}"
    pages = [f"/api/files/{record['id']}/pages/{i}?workspace={workspace}" for i in range(1, record["_pages"] + 1)] if record["mime"] == "application/pdf" else [url]
    return {"id": record["id"], "filename": record["filename"], "mime": record["mime"], "size": record["size"], "url": url, "page_urls": pages}


def validate_and_store(workspace, exam_id, filename, content):
    if not content or len(content) > MAX_FILE_SIZE:
        raise HTTPException(400, "文件为空或超过 20 MiB")
    filename = Path(filename.replace("\\", "/")).name[:200]
    extension = Path(filename).suffix.lower()
    if extension not in (".jpg", ".jpeg", ".png", ".webp", ".pdf"):
        raise HTTPException(400, "只接受 JPG、PNG、WebP 和 PDF")
    doc = None
    mime = ""
    page_count = 1
    try:
        if extension == ".pdf":
            if not content.startswith(b"%PDF-"):
                raise ValueError("invalid PDF signature")
            doc = fitz.open(stream=content, filetype="pdf")
            if doc.is_encrypted or doc.page_count < 1 or doc.page_count > MAX_PDF_PAGES:
                raise HTTPException(400, "PDF 需未加密，且为 1–30 页；请先拆分过长文件")
            page_count = doc.page_count
            mime = "application/pdf"
        else:
            with Image.open(io.BytesIO(content)) as img:
                if img.format not in ("JPEG", "PNG", "WEBP") or img.width * img.height > 30_000_000:
                    raise ValueError("unsupported image")
                mime = {"JPEG": "image/jpeg", "PNG": "image/png", "WEBP": "image/webp"}[img.format]
                img.verify()
    except HTTPException:
        if doc:
            doc.close()
        raise
    except (Exception,) as exc:
        if doc:
            doc.close()
        raise HTTPException(400, "文件内容无法验证，请上传真实且完整的图片/PDF") from exc
    file_id = s.uid()
    root = s.directory(workspace) / "attachments" / file_id
    root.mkdir()
    try:
        (root / "original").write_bytes(content)
        if doc:
            for i in range(doc.page_count):
                page = doc[i]
                scale = min(1.7, 1800 / max(page.rect.width, page.rect.height, 1))
                pix = page.get_pixmap(matrix=fitz.Matrix(scale, scale), alpha=False)
                pix.save(root / f"page-{i + 1}.png")
            doc.close()
        return {"id": file_id, "exam_id": exam_id, "filename": filename or "paper", "mime": mime, "size": len(content), "_pages": page_count, "_directory": file_id}
    except Exception:
        if doc:
            doc.close()
        # This directory is freshly generated by this function; never a caller-supplied path.
        for p in root.iterdir():
            if p.is_file():
                p.unlink()
        root.rmdir()
        raise HTTPException(400, "无法生成预览，请检查文件是否损坏")


def media_path(workspace, attachment, page=None):
    root = s.directory(workspace) / "attachments" / attachment["_directory"]
    path = root / (f"page-{page}.png" if page is not None else "original")
    if not path.is_file():
        raise HTTPException(404, "原件或预览不存在")
    return path


def image_for_model(workspace, attachment, page):
    path = media_path(workspace, attachment, page if attachment["mime"] == "application/pdf" else None)
    with Image.open(path) as img:
        img = ImageOps.exif_transpose(img).convert("RGB")
        img.thumbnail((2000, 2000))
        out = io.BytesIO()
        img.save(out, format="JPEG", quality=88)
        return out.getvalue()
