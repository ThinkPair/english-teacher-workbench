"""Build Tabler outline PNG data URIs from a local, pinned SVG source bundle.

Default builds offline. --fetch downloads the fixed official sources explicitly.
--check verifies generated output without changing it. Build dependency: PyMuPDF.
The mini program itself has no renderer or network dependency for these icons.
"""
from __future__ import annotations

import argparse
import base64
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
BUNDLE = ROOT / 'scripts' / 'ui-icons-sources.json'
OUTPUT = ROOT / 'miniprogram' / 'lib' / 'ui-icons.js'
LICENSE = ROOT / 'miniprogram' / 'lib' / 'UI_ICONS_LICENSE.txt'
REVISION = 'a4ce1404bc6d24d3c365afe7b258d6bf6f48d62d'
BASE = f'https://raw.githubusercontent.com/tabler/tabler-icons/{REVISION}'
ICONS = {
    'book2': 'book-2', 'users': 'users', 'databaseExport': 'database-export',
    'helpCircle': 'help-circle', 'search': 'search', 'plus': 'plus',
    'chevronRight': 'chevron-right', 'chevronLeft': 'chevron-left',
    'check': 'check', 'adjustmentsHorizontal': 'adjustments-horizontal',
}
COLORS = {'ink': '#202631', 'muted': '#737C89', 'accent': '#CB4A20', 'white': '#FFFFFF'}
SIZE = 96


def digest(value: str) -> str:
    return hashlib.sha256(value.encode('utf-8')).hexdigest()


def download(url: str) -> str:
    request = urllib.request.Request(url, headers={'User-Agent': 'Local-UI-Icon-Builder'})
    with urllib.request.urlopen(request, timeout=30) as response:
        data = response.read(128 * 1024 + 1)
    if len(data) > 128 * 1024:
        raise ValueError('Unexpectedly large official icon source')
    return data.decode('utf-8')


def validate_svg(source: str) -> None:
    if '<!DOCTYPE' in source.upper() or '<!ENTITY' in source.upper():
        raise ValueError('SVG entities are not allowed')
    root = ET.fromstring(source)
    allowed = {'svg', 'path', 'line', 'polyline', 'polygon', 'rect', 'circle', 'ellipse', 'g'}
    if root.tag.split('}')[-1] != 'svg' or root.get('viewBox') != '0 0 24 24':
        raise ValueError('Expected an official 24 by 24 outline SVG')
    for element in root.iter():
        if element.tag.split('}')[-1] not in allowed:
            raise ValueError('Unexpected active or external SVG element')
        for attr, value in element.attrib.items():
            local_name = attr.split('}')[-1].lower()
            if local_name.startswith('on') or local_name in {'href', 'src', 'style'} or 'url(' in value.lower():
                raise ValueError('External or executable SVG attributes are not allowed')
    if 'currentColor' not in source:
        raise ValueError('Expected a recolorable outline icon')


def fetch_bundle() -> dict:
    def fetch_icon(item: tuple[str, str]) -> tuple[str, dict]:
        key, filename = item
        url = f'{BASE}/icons/outline/{filename}.svg'
        source = download(url)
        validate_svg(source)
        return key, {'name': filename, 'url': url, 'sha256': digest(source), 'svg': source}

    with ThreadPoolExecutor(max_workers=5) as pool:
        sources = dict(pool.map(fetch_icon, ICONS.items()))
    license_text = download(f'{BASE}/LICENSE')
    if 'MIT License' not in license_text or 'Permission is hereby granted' not in license_text:
        raise ValueError('The pinned official license must remain MIT')
    return {
        'repository': 'https://github.com/tabler/tabler-icons',
        'revision': REVISION, 'family': 'outline', 'size': SIZE, 'colors': COLORS,
        'license': {'url': f'{BASE}/LICENSE', 'sha256': digest(license_text), 'text': license_text},
        'icons': sources,
    }


def verify_bundle(bundle: dict) -> None:
    if bundle['revision'] != REVISION or list(bundle['icons']) != list(ICONS):
        raise ValueError('Source bundle does not match the fixed icon selection/revision')
    if bundle['colors'] != COLORS or bundle['size'] != SIZE:
        raise ValueError('Source bundle rendering options do not match this generator')
    for key, filename in ICONS.items():
        entry = bundle['icons'][key]
        if entry['name'] != filename or entry['url'] != f'{BASE}/icons/outline/{filename}.svg':
            raise ValueError('Unexpected icon provenance')
        if digest(entry['svg']) != entry['sha256']:
            raise ValueError('Source SVG checksum mismatch')
        validate_svg(entry['svg'])
    if digest(bundle['license']['text']) != bundle['license']['sha256']:
        raise ValueError('License checksum mismatch')


def generate(bundle: dict) -> tuple[str, str]:
    import fitz
    lines = [
        "'use strict';",
        '// Generated by scripts/build_ui_icons.py; do not edit encoded assets by hand.',
        f'// Tabler Icons outline, MIT, official commit {REVISION}.',
        '// Attribution and full license: UI_ICONS_LICENSE.txt.',
        '// 96 x 96 transparent PNG data URIs. No runtime network or renderer.',
        'const icons = {',
    ]
    for key, entry in bundle['icons'].items():
        lines.append(f'  {key}: Object.freeze({{')
        for color_name, color in COLORS.items():
            colored = entry['svg'].replace('currentColor', color)
            with fitz.open(stream=colored.encode('utf-8'), filetype='svg') as document:
                page = document[0]
                pixmap = page.get_pixmap(matrix=fitz.Matrix(SIZE / page.rect.width, SIZE / page.rect.height), alpha=True)
                if (pixmap.width, pixmap.height, pixmap.alpha) != (SIZE, SIZE, 1):
                    raise ValueError('Unexpected rendered icon dimensions or alpha')
                encoded = base64.b64encode(pixmap.tobytes('png')).decode('ascii')
            lines.append(f'    {color_name}: "data:image/png;base64,{encoded}",')
        lines.append('  }),')
    lines += ['};', 'module.exports = Object.freeze(icons);', '']
    attribution = (
        'Tabler Icons outline — local UI subset\n'
        'Official repository: https://github.com/tabler/tabler-icons\n'
        f'Pinned commit: {REVISION}\n'
        'Local changes: recolored to four fixed theme colors and rendered to transparent 96x96 PNG.\n'
        'Original SVGs, source URLs and SHA-256 checksums: scripts/ui-icons-sources.json.\n'
        'Rebuild offline with: python scripts/build_ui_icons.py\n\n'
    )
    return '\n'.join(lines), attribution + bundle['license']['text'].rstrip() + '\n'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fetch', action='store_true', help='Fetch the pinned official sources explicitly')
    parser.add_argument('--check', action='store_true', help='Compare generated output without writing it')
    args = parser.parse_args()
    if args.fetch and args.check:
        parser.error('--fetch and --check must be used separately')
    bundle = fetch_bundle() if args.fetch else json.loads(BUNDLE.read_text(encoding='utf-8'))
    verify_bundle(bundle)
    js, license_text = generate(bundle)
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != js or LICENSE.read_text(encoding='utf-8') != license_text:
            raise SystemExit('Generated UI icons differ; rebuild with the pinned sources and renderer')
        print('PASS: 10 official outline icons, 40 PNG variants, source checksums and offline rebuild')
        return
    if args.fetch:
        BUNDLE.write_text(json.dumps(bundle, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
    OUTPUT.write_text(js, encoding='utf-8', newline='\n')
    LICENSE.write_text(license_text, encoding='utf-8', newline='\n')
    print(f'Generated {OUTPUT.name}: {len(ICONS)} icons / {len(ICONS) * len(COLORS)} PNG variants / {len(js.encode("utf-8"))} bytes')


if __name__ == '__main__':
    main()
